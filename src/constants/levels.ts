const LEVELS_BY_ID: Map<string, LevelConfig> = new Map(LEVELS.map((l) => [l.id, l]));

export const getLevel = (id: string): LevelConfig | undefined => LEVELS_BY_ID.get(id);

export const getLevelsForUnit = (unitId: string): LevelConfig[] =>
  LEVELS.filter((l) => l.unitId === unitId);

/** Returns the next level after `id`, or `undefined` if it is the last level. */
export const getNextLevelId = (id: string): string | undefined => {
  const idx = LEVELS.findIndex((l) => l.id === id);
  if (idx < 0 || idx >= LEVELS.length - 1) return undefined;
  return LEVELS[idx + 1].id;
};
